const regionsContainer = document.getElementById("regions");
const filters = document.querySelectorAll(".filter");
const modal = document.getElementById("modal");
const modalContent = document.getElementById("modalContent");
const modalClose = document.getElementById("modalClose");

function getTypeClass(line) {
  if (line.type === "Травяной") return "grass";
  if (line.type === "Огненный") return "fire";
  return "water";
}

function getStageLabel(index) {
  if (index === 0) return "Базовая форма";
  if (index === 1) return "Первая эволюция";
  return "Финальная эволюция";
}

function renderRegions(selectedRegion = "all") {
  const visible = selectedRegion === "all"
    ? regions
    : regions.filter((region) => region.name === selectedRegion);

  regionsContainer.innerHTML = visible.map((region) => `
    <section class="region">
      <div class="region-title">
        <h2>${region.name}</h2>
        <span>${region.generation}</span>
      </div>

      <div class="lines">
        ${region.lines.map((line, lineIndex) => {
          const baseStage = line.stages[0];

          return `
            <article class="pokemon-line">
              <div class="line-title">
                <h3>${line.type} стартовый</h3>
                <span class="type ${getTypeClass(line)}">${line.type}</span>
              </div>

              <button
                class="starter-button"
                data-region="${region.name}"
                data-line="${lineIndex}"
                data-stage="0"
              >
                <img src="${artwork(baseStage.id)}" alt="${baseStage.name}">
                <span>
                  <span class="starter-name">${baseStage.name}</span>
                  <span class="starter-hint">Базовая форма · нажмите для подробностей</span>
                </span>
              </button>
            </article>
          `;
        }).join("")}
      </div>
    </section>
  `).join("");
}

function renderPokemonDetails(regionName, lineIndex, stageIndex) {
  const region = regions.find((item) => item.name === regionName);
  const line = region.lines[lineIndex];
  const stage = line.stages[stageIndex];

  modalContent.innerHTML = `
    <div class="pokemon-hero">
      <img src="${artwork(stage.id)}" alt="${stage.name}">
      <div>
        <h2>${stage.name}</h2>
        <p>
          <strong>Регион:</strong> ${region.name}<br>
          <strong>Тип линии:</strong> ${line.type}<br>
          <strong>Стадия:</strong> ${getStageLabel(stageIndex)}<br>
          <strong>Эволюция:</strong> ${stage.level}
        </p>
        <p>${stage.description}</p>
      </div>
    </div>

    <div class="detail-block">
      <h3>Питание</h3>
      <p>${stage.diet}</p>
    </div>

    <div class="detail-block">
      <h3>Сильные и слабые стороны</h3>
      <p>${stage.strengths}</p>
      <p>${stage.weaknesses}</p>
    </div>

    <div class="detail-block">
      <h3>Специальные атаки</h3>
      <p>${translateAttacks(stage.attacks)}</p>
    </div>

    <div class="evolutions">
      <h3>Стадии эволюции</h3>

      <div class="evolution-list">
        ${line.stages.map((item, index) => `
          <button
            class="evolution-button ${index === stageIndex ? "selected" : ""}"
            data-region="${regionName}"
            data-line="${lineIndex}"
            data-stage="${index}"
          >
            <img src="${artwork(item.id)}" alt="${item.name}">
            <strong>${item.name}</strong>
            <span>${getStageLabel(index)}</span>
          </button>
        `).join("")}
      </div>
    </div>
  `;
}

function openPokemon(regionName, lineIndex, stageIndex) {
  renderPokemonDetails(regionName, lineIndex, stageIndex);

  modal.classList.add("open");
  modal.setAttribute("aria-hidden", "false");
  document.body.style.overflow = "hidden";
  modalContent.scrollTop = 0;
}

function closeModal() {
  modal.classList.remove("open");
  modal.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";
}

document.addEventListener("click", (event) => {
  const starter = event.target.closest(".starter-button");
  const evolution = event.target.closest(".evolution-button");

  if (starter) {
    openPokemon(
      starter.dataset.region,
      Number(starter.dataset.line),
      Number(starter.dataset.stage)
    );
    return;
  }

  if (evolution) {
    renderPokemonDetails(
      evolution.dataset.region,
      Number(evolution.dataset.line),
      Number(evolution.dataset.stage)
    );
    return;
  }

  if (event.target === modal) {
    closeModal();
  }
});

modalClose.addEventListener("click", closeModal);

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    closeModal();
  }
});

filters.forEach((filter) => {
  filter.addEventListener("click", () => {
    filters.forEach((item) => item.classList.remove("active"));
    filter.classList.add("active");
    renderRegions(filter.dataset.region);
  });
});

