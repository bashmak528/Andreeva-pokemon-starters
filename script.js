function escapeRegExp(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function translateAttacks(text) {
  let result = text;

  const entries = Object.entries(attackTranslations)
    .sort((a, b) => b[0].length - a[0].length);

  entries.forEach(([englishName, russianName]) => {
    const pattern = new RegExp(`\\b${escapeRegExp(englishName)}\\b`, "gi");
    result = result.replace(pattern, russianName);
  });

  return result;
}

